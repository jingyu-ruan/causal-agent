import { generateCsv, type FrozenStudy, type Scenario, type SyntheticParameters } from "./synthetic-data"

const UPSTREAM = "https://causal-agent.onrender.com"
const REQUEST_HEADERS = ["content-type", "x-workspace-key", "x-deepseek-api-key"]
const RESPONSE_HEADERS = ["content-type", "content-disposition", "x-synthetic-source"]

async function upstream(path: string, init?: RequestInit) {
  const response = await fetch(UPSTREAM + path, { ...init, redirect: "manual", signal: AbortSignal.timeout(path === "/ready" ? 8000 : 120000) })
  if (response.status >= 300 && response.status < 400) throw new Error("Unexpected analysis-service redirect")
  return response
}

async function referenceStudy(scenario: Scenario | "did") {
  const did = scenario === "did"
  const request = {
    title: did ? "Reference study / Regional rollout" : "Reference study / " + scenario,
    business_question: did ? "Did the regional rollout improve the target outcome?" : "Should guided onboarding roll out to all eligible new users?",
    hypothesis: did ? "The rollout increases the target outcome after adoption." : "Guided onboarding increases activation without increasing support contacts.",
    population: did ? "Eligible regions" : "Eligible new users",
    intervention: did ? "Regional product rollout" : "Guided onboarding",
    comparator: "Current experience",
    design_type: did ? "difference_in_differences" : "randomized_ab",
    unit: did ? "region_id" : "user_id",
    estimand: did ? "att" : "ate",
    primary_metric: { name: did ? "outcome" : "activated_within_7d", kind: did ? "continuous" : "binary", direction: "higher_is_better", minimum_effect: did ? 1 : 0.01 },
    guardrails: did ? [] : [{ name: "support_contact_rate", kind: "binary", direction: "lower_is_better", minimum_effect: 0, harm_tolerance: 0.01 }],
    ...(did ? { treatment_start: 5, minimum_pre_periods: 5 } : { baseline_value: 0.2, expected_control_allocation: 0.5, expected_treatment_allocation: 0.5, expected_daily_units: 5000 }),
    observation_window_days: did ? 1 : 7,
    notes: "Synthetic reference example. Data is generated by the Sites compatibility adapter; deterministic Python produces diagnostics, estimates and the decision.",
  }
  const frozenResponse = await upstream("/api/studies/design", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(request) })
  if (!frozenResponse.ok) return frozenResponse
  const study = await frozenResponse.json() as FrozenStudy
  const { csv } = generateCsv(study, { baseline_value: did ? 10 : 0.2, outcome_standard_deviation: 0.2 }, did ? undefined : scenario)
  const mapping = {
    unit_col: study.contract.unit,
    treatment_col: "treatment",
    ...(did ? { time_col: "time" } : {}),
    metric_cols: Object.fromEntries([study.contract.primary_metric, ...study.contract.guardrails].map((metric) => [metric.name, metric.name])),
    covariate_cols: {},
    dimension_cols: did ? ["region_type"] : ["platform", "audience"],
  }
  const form = new FormData()
  form.append("file", new Blob([csv], { type: "text/csv" }), "reference-study-" + scenario + ".csv")
  form.append("mapping_json", JSON.stringify(mapping))
  form.append("options_json", JSON.stringify({ transformation_log: [] }))
  const analyzed = await upstream("/api/studies/" + encodeURIComponent(study.study_id) + "/analyze", { method: "POST", body: form })
  if (!analyzed.ok) return analyzed
  return upstream("/api/studies/" + encodeURIComponent(study.study_id))
}

/** A same-origin boundary for the existing Python service. Never forward Site cookies. */
export async function proxyCausalApi(request: Request): Promise<Response> {
  const url = new URL(request.url)
  const path = url.pathname.slice("/backend".length)
  if (!/^\/(ready|health)$/.test(path) && !/^\/api\/(studies|conversations|agent)(\/|$)/.test(path)) {
    return Response.json({ detail: "Unknown analysis route" }, { status: 404 })
  }
  if (!["GET", "POST", "PUT", "DELETE"].includes(request.method)) {
    return Response.json({ detail: "Method not supported" }, { status: 405 })
  }
  try {
    const syntheticMatch = path.match(/^\/api\/studies\/([^/]+)\/synthetic-data$/)
    if (syntheticMatch && request.method === "POST") {
      const parameters = await request.json().catch(() => null) as SyntheticParameters | null
      if (!parameters || typeof parameters !== "object" || Array.isArray(parameters) ||
        (parameters.baseline_value !== undefined && (typeof parameters.baseline_value !== "number" || !Number.isFinite(parameters.baseline_value))) ||
        (parameters.outcome_standard_deviation !== undefined && (typeof parameters.outcome_standard_deviation !== "number" || !Number.isFinite(parameters.outcome_standard_deviation) || parameters.outcome_standard_deviation <= 0))) {
        return Response.json({ detail: "Synthetic-data parameters must be finite numbers." }, { status: 422 })
      }
      const frozenResponse = await upstream("/api/studies/" + syntheticMatch[1])
      if (!frozenResponse.ok) return frozenResponse
      const frozen = await frozenResponse.json() as FrozenStudy
      const generated = generateCsv(frozen, parameters)
      return new Response(generated.csv, { headers: {
        "Content-Type": "text/csv; charset=utf-8",
        "Content-Disposition": 'attachment; filename="' + syntheticMatch[1] + '-synthetic.csv"',
        "Cache-Control": "no-store",
        "X-Synthetic-Source": "frozen-design-contract",
      } })
    }
    const referenceMatch = path.match(/^\/api\/studies\/demo\/(did|rct\/(go|hold|insufficient_evidence))$/)
    if (referenceMatch && request.method === "GET") return await referenceStudy((referenceMatch[2] ?? "did") as Scenario | "did")

    const headers = new Headers()
    for (const name of REQUEST_HEADERS) {
      const value = request.headers.get(name)
      if (value) headers.set(name, value)
    }
    const response = await upstream(path + url.search, {
      method: request.method,
      headers,
      body: ["GET", "HEAD"].includes(request.method) ? undefined : request.body,
    })
    const outgoing = new Headers({ "Cache-Control": "no-store" })
    for (const name of RESPONSE_HEADERS) {
      const value = response.headers.get(name)
      if (value) outgoing.set(name, value)
    }
    return new Response(response.body, { status: response.status, headers: outgoing })
  } catch (error) {
    if (import.meta.env.DEV) console.warn("Python service connection failed:", error instanceof Error ? error.message : "Fetch failed")
    return Response.json({ detail: "The Python analysis service is warming or temporarily unavailable. Retry the connection." }, { status: 503, headers: { "Cache-Control": "no-store" } })
  }
}
